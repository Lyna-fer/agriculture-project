/** Retourne la liste de cultures pour un groupId (1, 2, ou 3) */
export function getCropsByGroup(groupId) {
  if (groupId === 1) return MARAICHERES;
  if (groupId === 2) return CEREALIÈRES;
  if (groupId === 3) return PERMANENTES;
  return [];
}

/** Trouve une culture par son id slug dans tous les groupes */
export function findCropById(id) {
  return (
    MARAICHERES.find((c) => c.id === id) ||
    CEREALIÈRES.find((c) => c.id === id) ||
    PERMANENTES.find((c) => c.id === id) ||
    null
  );
}

